#!/usr/bin/env node
// Zero-dependency minifier for css/*.css and js/**/*.js. Run: node scripts/build.mjs
// Keeps strings, templates, regexes and comments-in-strings intact; strips
// comments and redundant whitespace, then shaves safe punctuation spacing.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const banner = '/* generated by scripts/build.mjs */\n';

function walk(dir, ext, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(full, ext, out);
    else if (ent.isFile() && ent.name.endsWith(ext) && !ent.name.endsWith(`.min${ext}`)) out.push(full);
  }
  return out.sort();
}

// Tokenize into code / raw (strings, templates, regexes) / ws tokens.
function tokenize(src, detectRegex) {
  const tokens = [], modes = [];
  let i = 0;
  const pushWs = (nl) => {
    const last = tokens.at(-1);
    if (last && last.type === 'ws') {
      last.nl = last.nl || nl;
      last.value = last.nl ? '\n' : ' ';
    } else {
      tokens.push({ type: 'ws', value: nl ? '\n' : ' ', nl });
    }
  };
  const pushCode = (ch) => {
    const last = tokens.at(-1);
    if (last && last.type === 'code') last.value += ch;
    else tokens.push({ type: 'code', value: ch });
  };
  const isRegexStart = () => {
    let s = '';
    for (let k = tokens.length - 1; k >= 0 && s.length < 24; k--) {
      const t = tokens[k];
      if (t.type === 'ws') continue;
      if (t.type === 'raw') {
        if (!s) return t.value === '${';
        break;
      }
      s = t.value + s;
    }
    if (/\+\+$|--$/.test(s)) return false;
    return (
      /(^|[(\[{,:;=!&|?+\-*%~^<>])$/.test(s) ||
      /(?:^|[^.$\w])(return|typeof|case|delete|void|in|of|new|else|do|throw|await|yield)$/.test(s)
    );
  };

  while (i < src.length) {
    const mode = modes.at(-1)?.type ?? 'code';
    const c = src[i], n = src[i + 1];

    if (mode === 'line') {
      if (c === '\n') { modes.pop(); pushWs(true); }
      i++; continue;
    }
    if (mode === 'block') {
      if (c === '\n' || c === '\r') modes.at(-1).nl = true;
      if (c === '*' && n === '/') {
        const nl = !!modes.pop().nl;
        i += 2;
        pushWs(nl);
      } else i++;
      continue;
    }
    if (mode === 'single' || mode === 'double' || mode === 'regex' || mode === 'template') {
      const frame = modes.at(-1);
      if (c === '\\') { frame.buf += c + (n ?? ''); i += 2; continue; }
      if (mode === 'regex') {
        if (c === '[') frame.inClass = true;
        else if (c === ']') frame.inClass = false;
      }
      if (mode === 'template' && c === '$' && n === '{') {
        frame.buf += '${';
        tokens.push({ type: 'raw', value: frame.buf });
        frame.buf = '';
        modes.push({ type: 'expr', braces: 0 });
        i += 2; continue;
      }
      const closes = (mode === 'single' && c === "'") || (mode === 'double' && c === '"') ||
        (mode === 'regex' && c === '/' && !frame.inClass) || (mode === 'template' && c === '`');
      frame.buf += c;
      if (closes) {
        tokens.push({ type: 'raw', value: frame.buf });
        modes.pop();
      }
      i++; continue;
    }
    if (mode === 'expr') {
      if (c === '/' && n === '/') { modes.push({ type: 'line' }); i += 2; continue; }
      if (c === '/' && n === '*') { modes.push({ type: 'block', nl: false }); i += 2; continue; }
      if (c === "'" || c === '"' || c === '`') {
        modes.push({ type: c === '`' ? 'template' : c === "'" ? 'single' : 'double', buf: c });
        i++; continue;
      }
      if (detectRegex && c === '/' && isRegexStart()) {
        modes.push({ type: 'regex', inClass: false, buf: c });
        i++; continue;
      }
      if (c === '{') { modes.at(-1).braces++; pushCode(c); i++; continue; }
      if (c === '}') {
        if (modes.at(-1).braces === 0) {
          modes.pop();
          const tpl = modes.at(-1);
          tpl.buf = '}';
        } else {
          modes.at(-1).braces--;
          pushCode(c);
        }
        i++; continue;
      }
      if (/\s/.test(c)) {
        let j = i, nl = false;
        while (j < src.length && /\s/.test(src[j])) { if (src[j] === '\n' || src[j] === '\r') nl = true; j++; }
        pushWs(nl); i = j; continue;
      }
      pushCode(c); i++; continue;
    }

    // top-level code
    if (detectRegex && c === '/' && n === '/') { modes.push({ type: 'line' }); i += 2; continue; }
    if (c === '/' && n === '*') { modes.push({ type: 'block', nl: false }); i += 2; continue; }
    if (c === "'" || c === '"' || c === '`') {
      modes.push({ type: c === '`' ? 'template' : c === "'" ? 'single' : 'double', buf: c });
      i++; continue;
    }
    if (detectRegex && c === '/' && isRegexStart()) {
      modes.push({ type: 'regex', inClass: false, buf: c });
      i++; continue;
    }
    if (/\s/.test(c)) {
      let j = i, nl = false;
      while (j < src.length && /\s/.test(src[j])) { if (src[j] === '\n' || src[j] === '\r') nl = true; j++; }
      pushWs(nl); i = j; continue;
    }
    pushCode(c); i++;
  }
  return tokens;
}

function minifyCSS(src) {
  const tokens = tokenize(src, false);
  const out = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (t.type === 'raw') { out.push(t.value); continue; }
    if (t.type === 'code') {
      let v = t.value.replace(/;}/g, '}');
      const next = tokens[i + 1], after = tokens[i + 2];
      if (v.endsWith(';') && ((next?.type === 'code' && next.value.startsWith('}')) ||
          (next?.type === 'ws' && after?.type === 'code' && after.value.startsWith('}')))) {
        v = v.slice(0, -1);
      }
      if (v) out.push(v);
      continue;
    }
    const prev = out.at(-1);
    const next = tokens[i + 1]?.value;
    if (!prev || !next) continue;
    const p = prev.at(-1), nx = next[0];
    if ('{};,>:('.includes(p) || '{};,>)'.includes(nx)) continue;
    out.push(' ');
  }
  return out.join('').trim();
}

function minifyJS(src, file) {
  const tokens = tokenize(src, true);
  const out = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (t.type !== 'ws') { out.push(t.value); continue; }
    const prev = out.at(-1);
    const next = tokens[i + 1]?.value;
    if (!prev || !next) continue;
    const p = prev.at(-1), nx = next[0];
    const pCode = tokens[i - 1]?.type === 'code' || prev.endsWith('${');
    const nCode = tokens[i + 1]?.type === 'code' || next.startsWith('}');
    if ((pCode && '([{,;?:'.includes(p)) || (nCode && ')]},;?:'.includes(nx))) continue;
    if (!t.nl && pCode && nCode && p === ')' && nx === '{') continue;
    if (pCode && p === '=' && nx !== '=' && nx !== '>') continue;
    if (nCode && nx === '=' && !'!=<>+-*/%&|^?'.includes(p)) continue;
    out.push(t.nl ? '\n' : ' ');
  }
  const min = out.join('').trim();
  try {
    new Function(min);
    new vm.Script(min, { filename: file });
  } catch (err) {
    throw new Error(`${file}: minified JS failed syntax check: ${err.message}`);
  }
  return min;
}

let beforeCss = 0, afterCss = 0, beforeJs = 0, afterJs = 0;
const cssFiles = walk(path.join(root, 'css'), '.css');
const jsFiles = walk(path.join(root, 'js'), '.js');

for (const f of cssFiles) {
  const src = fs.readFileSync(f, 'utf8');
  const min = banner + minifyCSS(src) + '\n';
  fs.writeFileSync(f.replace(/\.css$/, '.min.css'), min);
  beforeCss += Buffer.byteLength(src);
  afterCss += Buffer.byteLength(min);
}
for (const f of jsFiles) {
  const src = fs.readFileSync(f, 'utf8');
  const min = banner + minifyJS(src, path.relative(root, f)) + '\n';
  fs.writeFileSync(f.replace(/\.js$/, '.min.js'), min);
  beforeJs += Buffer.byteLength(src);
  afterJs += Buffer.byteLength(min);
}

const pct = (a, b) => (a ? ((1 - b / a) * 100).toFixed(1) : '0.0');
console.log(`CSS (${cssFiles.length} files): ${(beforeCss / 1024).toFixed(1)} KB -> ${(afterCss / 1024).toFixed(1)} KB (${pct(beforeCss, afterCss)}% saved)`);
console.log(`JS  (${jsFiles.length} files): ${(beforeJs / 1024).toFixed(1)} KB -> ${(afterJs / 1024).toFixed(1)} KB (${pct(beforeJs, afterJs)}% saved)`);
