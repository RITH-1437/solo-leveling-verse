"""Write js/media-index.js: the list of every artwork and video file in assets/.

Artwork is found by naming convention (assets/characters/<id>.webp,
assets/shadows/<id>.webp, ...). With this index the browser only requests
files that really exist instead of probing every candidate path, so the
console stays free of 404s and entries without art show their generated sigil.

Run from anywhere after adding, renaming or removing media:
    python tools/build_media_index.py

It also warns about files whose name matches no entity id in js/data/.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ["characters", "hunters", "monarchs", "shadows", "weapons", "monsters", "backgrounds", "skills", "guilds", "videos"]
MEDIA = {".webp", ".png", ".jpg", ".jpeg", ".avif", ".mp4", ".webm"}


def known_ids():
    ids = set()
    for f in (ROOT / "js" / "data").glob("*.js"):
        ids.update(re.findall(r'\bid:\s*"([a-z0-9_]+)"', f.read_text(encoding="utf-8")))
    return ids


def main():
    files = sorted(
        p.relative_to(ROOT).as_posix()
        for folder in FOLDERS
        if (ROOT / "assets" / folder).is_dir()
        for p in (ROOT / "assets" / folder).rglob("*")
        if p.is_file() and p.suffix.lower() in MEDIA
    )
    ids = known_ids()
    orphans = [f for f in files if Path(f).stem not in ids]
    out = ROOT / "js" / "media-index.js"
    body = ",\n  ".join(json.dumps(f, ensure_ascii=False) for f in files)
    out.write_text(
        "/* GENERATED by tools/build_media_index.py, do not edit by hand.\n"
        "   Every media file under assets/; pages only request paths listed here. */\n"
        f"window.MEDIA_INDEX = [{chr(10) + '  ' + body + chr(10) if files else ''}];\n",
        encoding="utf-8", newline="\n",
    )
    print(f"wrote {out.relative_to(ROOT).as_posix()} ({len(files)} files)")
    for f in orphans:
        print(f"  warning: {f} matches no entity id in js/data/")


if __name__ == "__main__":
    main()
